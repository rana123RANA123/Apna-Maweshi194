export function formatPKR(amount: number, language: Language = 'en'): string {
  if (language === 'ur') {
    if (amount >= 10000000) {
      const crore = (amount / 10000000).toFixed(2);
      return `${crore} کروڑ روپے`;
    } else if (amount >= 100000) {
      const lakh = (amount / 100000).toFixed(2);
      return `${lakh} لاکھ روپے`;
    }
    return `${amount.toLocaleString('ur-PK')} روپے`;
  }

  // English formatting with Lakh / Crore representation standard in Pakistan
  if (amount >= 10000000) {
    const crore = (amount / 10000000).toFixed(2).replace(/\.00$/, '');
    return `PKR ${crore} Crore`;
  } else if (amount >= 100000) {
    const lakh = (amount / 100000).toFixed(2).replace(/\.00$/, '');
    return `PKR ${lakh} Lakh`;
  }
  return `PKR ${amount.toLocaleString('en-PK')}`;
}

export function formatTeeth(teeth: string, language: Language = 'en'): string {
  if (teeth === 'kheera') {
    return language === 'ur' ? 'کھیرا (دودھ کے دانت)' : 'Milk Teeth (Kheera)';
  }
  return language === 'ur' ? `${teeth} دانت` : `${teeth} Teeth (Daant)`;
}
